-- Migración ADITIVA para una base existente con el esquema actual de Rodatours.
-- Ejecutar como propietario del esquema después de una copia de seguridad.
-- No borra ni reconstruye reservas. No inventa un historial retroactivo.
BEGIN;
CREATE TABLE reservation_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    previous_status VARCHAR(15),
    status VARCHAR(15) NOT NULL,
    occurred_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    actor_role VARCHAR(30) NOT NULL,
    actor_email VARCHAR(255),
    reason TEXT
);
CREATE INDEX ix_history_reservation_time ON reservation_history(reservation_id, occurred_at, id);
COMMIT;
